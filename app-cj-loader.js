(function () {
  const CATALOG_URL = "./data/catalog.json";

  function normalizeProduct(product, index) {
    const regularPrice =
      typeof product.price === "number" &&
      Number.isFinite(product.price) &&
      product.price > 0
        ? product.price
        : null;

    const salePrice =
      typeof product.salePrice === "number" &&
      Number.isFinite(product.salePrice) &&
      product.salePrice > 0
        ? product.salePrice
        : null;

    /*
      A product is considered on sale only when:
      - regular price exists
      - sale price exists
      - sale price is greater than zero
      - sale price is lower than regular price
    */
    const hasSale =
      regularPrice !== null &&
      salePrice !== null &&
      salePrice < regularPrice;

    /*
      ZOVARO must use the English fields generated by
      the automatic translation pipeline.

      Brand and advertiser names are preserved because
      they are proper names.
    */
    const englishName =
      product.englishTitle ||
      product.title ||
      product.brand ||
      product.advertiserName ||
      "ZOVARO Offer";

    const englishDescription =
      product.englishDescription ||
      product.description ||
      `${product.brand ? product.brand + " — " : ""}${englishName}`;

    const englishCategory =
      product.englishCategory ||
      product.category ||
      "Featured";

    const image =
      product.imageLink ||
      (
        Array.isArray(product.additionalImageLinks) &&
        product.additionalImageLinks.length
          ? product.additionalImageLinks[0]
          : ""
      );

    const productId =
      product.id != null
        ? String(product.id)
        : String(100000 + index);

    const discount =
      hasSale
        ? (
            Number.isFinite(Number(product.discountPercentage)) &&
            Number(product.discountPercentage) > 0
              ? `${Number(product.discountPercentage).toFixed(0)}%`
              : `${Math.round(
                  ((regularPrice - salePrice) / regularPrice) * 100
                )}%`
          )
        : null;

    return {
      id: productId,

      /*
        English content for ZOVARO.
      */
      name: englishName,

      description: englishDescription,

      category: englishCategory,

      /*
        Advertiser and brand names are kept unchanged.
      */
      merchant:
        product.advertiserName ||
        "CJ Affiliate",

      brand:
        product.brand ||
        "",

      /*
        Correct price logic:
        invalid/zero sale prices are never treated as sales.
      */
      price:
        hasSale
          ? salePrice
          : regularPrice,

      oldPrice:
        hasSale
          ? regularPrice
          : null,

      discount,

      currency:
        product.currency ||
        "USD",

      image,

      type: "affiliate",

      source:
        product.source ||
        "CJ",

      network:
        product.network ||
        "CJ Affiliate",

      clickUrl:
        product.clickUrl ||
        product.destination ||
        "",

      destination:
        product.destination ||
        "",

      advertiserId:
        product.advertiserId ||
        "",

      adId:
        product.adId ||
        "",

      joinedStatus:
        product.joinedStatus === true
    };
  }

  async function loadAffiliateCatalog() {
    try {
      const response = await fetch(
        `${CATALOG_URL}?v=${Date.now()}`,
        {
          cache: "no-store"
        }
      );

      if (!response.ok) {
        throw new Error(
          `Catalog request failed: ${response.status}`
        );
      }

      const catalog = await response.json();

      if (
        !catalog ||
        !Array.isArray(catalog.products) ||
        catalog.products.length === 0
      ) {
        console.info(
          "ZOVARO CJ loader: no products available."
        );
        return;
      }

      const ENABLED_NETWORKS =
        Array.isArray(catalog.sources)
          ? catalog.sources
              .filter(source =>
                source &&
                source.status === "active"
              )
              .map(source =>
                source.network
              )
          : [];

      const affiliateProducts =
        catalog.products
          .filter(product =>
            product &&
            ENABLED_NETWORKS.includes(product.network) &&
            product.joinedStatus === true &&
            typeof product.destination === "string" &&
            product.destination.trim() !== "" &&
            typeof product.imageLink === "string" &&
            product.imageLink.trim() !== "" &&

            /*
              English title and description must exist
              before the product enters ZOVARO.
            */
            typeof product.englishTitle === "string" &&
            product.englishTitle.trim() !== "" &&
            typeof product.englishDescription === "string" &&
            product.englishDescription.trim() !== ""
          )
          .map(normalizeProduct)
          .filter(product =>
            product.image &&
            product.name &&
            product.description
          );

      if (!affiliateProducts.length) {
        console.info(
          "ZOVARO CJ loader: no usable English products."
        );
        return;
      }

      PRODUCTS.splice(
        0,
        PRODUCTS.length,
        ...affiliateProducts
      );

      console.info(
        `ZOVARO affiliate loader: ${affiliateProducts.length} real English products loaded.`
      );

      if (typeof render === "function") {
        render();
      }

    } catch (error) {
      console.warn(
        "ZOVARO CJ loader:",
        error
      );
    }
  }

  loadAffiliateCatalog();
})();
